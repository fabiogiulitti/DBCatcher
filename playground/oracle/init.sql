CREATE OR REPLACE PROCEDURE copy_characters AS
BEGIN
    INSERT INTO characters (name, universe, first_appearance, creator, gender, species, alignment)
    SELECT name || ' (copy)', universe, first_appearance, creator, gender, species, alignment
    FROM characters
    WHERE ROWNUM <= 1;
END;
