    id              NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name            VARCHAR2(100) NOT NULL,
    universe        VARCHAR2(100),
    first_appearance DATE,
    creator         VARCHAR2(100),
    gender          VARCHAR2(10),
    species         VARCHAR2(50),
    alignment       VARCHAR2(20)
);

